// Generates extensions/pig-claude-bridge/internal/models/catalog_gen.go from
// the Anthropic catalog of @earendil-works/pi-ai.
//
// Usage (any working directory):
//   node scripts/dev/gen-catalog.mjs <typescript-clone> <this-repo>
// e.g. node scripts/dev/gen-catalog.mjs ~/github.com/pi-claude-bridge ~/github.com/pig-claude-bridge
//
// pi-ai is loaded from <typescript-clone>/node_modules, so the clone needs its
// dependencies installed. The version is read from pi-ai's package.json.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, join } from "node:path";
import { pathToFileURL } from "node:url";

const [cloneArg, repoArg] = process.argv.slice(2);
if (!cloneArg || !repoArg) {
	console.error("usage: node gen-catalog.mjs <typescript-clone> <this-repo>");
	process.exit(2);
}
const piAiDir = join(resolve(cloneArg), "node_modules", "@earendil-works", "pi-ai");
const { version } = JSON.parse(readFileSync(join(piAiDir, "package.json"), "utf8"));
const { getModels } = await import(pathToFileURL(join(piAiDir, "dist", "compat.js")).href);

// Sorted keys at every depth keep the output stable across pi-ai releases.
const sortKeys = (v) =>
	Array.isArray(v) ? v.map(sortKeys)
	: v && typeof v === "object" ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, sortKeys(v[k])]))
	: v;

const models = getModels("anthropic").map(sortKeys).sort((a, b) => a.id.localeCompare(b.id));
const lines = models.map((m) => JSON.stringify(m)).join(",\n");
if (lines.includes("`")) throw new Error("catalog contains a backtick; cannot embed as a raw string");

const source = `// Code generated by scripts/dev/gen-catalog.mjs from @earendil-works/pi-ai ${version}; DO NOT EDIT.

package models

import (
	"encoding/json"
	"sync"
)

// CatalogSource names the pi-ai release the embedded catalog was generated from.
const CatalogSource = "@earendil-works/pi-ai@${version}"

const catalogJSON = \`[
${lines}
]\`

var (
	catalogOnce    sync.Once
	catalogEntries []map[string]any
)

// Catalog returns pi-ai's Anthropic catalog entries with every field pi-ai carries.
// The result is shared and must not be modified.
func Catalog() []map[string]any {
	catalogOnce.Do(func() {
		if err := json.Unmarshal([]byte(catalogJSON), &catalogEntries); err != nil {
			panic("models: embedded catalog is invalid: " + err.Error())
		}
	})
	return catalogEntries
}
`;
writeFileSync(join(resolve(repoArg), "extensions", "pig-claude-bridge", "internal", "models", "catalog_gen.go"), source);
console.log(`wrote ${models.length} models from pi-ai ${version}`);
