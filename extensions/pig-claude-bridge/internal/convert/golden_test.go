// volatileValues matches what scripts/dev/golden-conversion.mjs replaces; the
// two apply the same rule to the text of each record.
var volatileValues = regexp.MustCompile(`("(?:uuid|parentUuid|timestamp|slug)":)"([^"]*)"|"((?:msg|req|toolu)_syn_[0-9a-f]+)"`)

func normalise(lines []string) []string {
	placeholders := map[string]string{}
	placeholder := func(value string) string {
		if _, ok := placeholders[value]; !ok {
			placeholders[value] = "<" + strconv.Itoa(len(placeholders)+1) + ">"
		}
		return placeholders[value]
	}
	out := make([]string, len(lines))
	for i, line := range lines {
		out[i] = volatileValues.ReplaceAllStringFunc(line, func(m string) string {
			sub := volatileValues.FindStringSubmatch(m)
			if sub[1] != "" {
				return sub[1] + `"` + placeholder(sub[2]) + `"`
			}
			return `"` + placeholder(sub[3]) + `"`
		})
	}
	return out
}

// topLevelKeys is the key sequence of a JSON object, read off the token stream.
func topLevelKeys(t *testing.T, line string) []string {
	t.Helper()
	dec := json.NewDecoder(strings.NewReader(line))
	if tok, err := dec.Token(); err != nil || tok != json.Delim('{') {
		t.Fatalf("not a JSON object: %s", line)
	}
	var keys []string
	for dec.More() {
		key, err := dec.Token()
		if err != nil {
			t.Fatal(err)
		}
		keys = append(keys, key.(string))
		var value json.RawMessage
		if err := dec.Decode(&value); err != nil {
			t.Fatal(err)
		}
	}
	return keys
}

// canonical parses a record and re-encodes it with sorted keys at every depth.
func canonical(t *testing.T, line string) string {
	t.Helper()
	var v any
	if err := json.Unmarshal([]byte(line), &v); err != nil {
		t.Fatal(err)
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(v); err != nil {
		t.Fatal(err)
	}
	return buf.String()
}

// TestGoldenPiHistory310 compares the records written for the 310-message
// fixture with those the TypeScript bridge writes (testdata, generated by
// scripts/dev/golden-conversion.mjs). Record and block field order must match
// exactly; free-form values (tool inputs and results) are compared after
// canonicalisation, because PiG delivers decoded maps that carry no key order.
func TestGoldenPiHistory310(t *testing.T) {
	anthropic, _, _, err := ConvertPiMessages(loadFixture(t), nil)
	if err != nil {
		t.Fatal(err)
	}
	session, err := ccsession.Create(ccsession.Options{
		SessionID: "00000000-0000-4000-8000-000000000000", ProjectPath: "/golden", Cwd: "/golden",
		GitBranch: "HEAD", ClaudeDir: t.TempDir(),
	})
	if err != nil {
		t.Fatal(err)
	}
	if err := session.ImportMessages(ccsession.RepairToolPairing(anthropic), nil); err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, raw := range session.Records() {
		got = append(got, string(raw))
	}
	got = normalise(got)

	data, err := os.ReadFile("testdata/golden-pi-history-310.jsonl")
	if err != nil {
		t.Fatal(err)
	}
	want := strings.Split(strings.TrimSuffix(string(data), "\n"), "\n")

	if len(got) != len(want) {
		t.Fatalf("record count: got %d, want %d", len(got), len(want))
	}
	for i := range want {
		if !reflect.DeepEqual(topLevelKeys(t, got[i]), topLevelKeys(t, want[i])) {
			t.Fatalf("line %d: top-level key order differs\n got: %s\nwant: %s", i+1, got[i], want[i])
		}
		if canonical(t, got[i]) != canonical(t, want[i]) {
			t.Fatalf("line %d: records differ\n got: %s\nwant: %s", i+1, got[i], want[i])
		}
	}
}
